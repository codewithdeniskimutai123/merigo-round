
import { useMemo, useState } from 'react'
import { toast } from 'sonner'

import Card from '../../../../../components/Card.jsx'
import Button from '../../../../../components/Button.jsx'

import {
  useSelectCycleDrawOption,
} from '../../../../../hooks/useCycles.js'

const EMPTY_OPTIONS = []

const CARD_DESIGNS = [
  {
    label: 'Mystery card',
    pattern: 'border-brand-600/30 bg-brand-600/5',
    decoration: 'bg-brand-600/20',
  },
  {
    label: 'Mystery card',
    pattern: 'border-border bg-surface-secondary',
    decoration: 'bg-text-muted/15',
  },
  {
    label: 'Mystery card',
    pattern: 'border-brand-600/20 bg-surface-secondary',
    decoration: 'bg-brand-600/15',
  },
  {
    label: 'Mystery card',
    pattern: 'border-border bg-brand-600/5',
    decoration: 'bg-brand-600/20',
  },
  {
    label: 'Mystery card',
    pattern: 'border-border bg-surface-secondary',
    decoration: 'bg-brand-600/10',
  },
  {
    label: 'Mystery card',
    pattern: 'border-brand-600/25 bg-brand-600/5',
    decoration: 'bg-text-muted/15',
  },
]

function getDrawProgress(drawData, orderData, options) {
  const remaining =
    drawData?.remaining_options ??
    options.length

  const total =
    drawData?.total_options ??
    drawData?.total_positions

  const remainingCount = Number(remaining)

  if (
    Number.isFinite(Number(total)) &&
    Number(total) > 0 &&
    Number.isFinite(remainingCount)
  ) {
    const totalCount = Number(total)
    const completed = Math.max(0, totalCount - remainingCount)

    return {
      total: totalCount,
      completed,
      remaining: remainingCount,
      percentage: Math.min(
        100,
        Math.max(0, (completed / totalCount) * 100),
      ),
    }
  }

  const completed =
    drawData?.draw_complete ||
    orderData?.draw_complete
      ? 1
      : 0

  return {
    total: null,
    completed,
    remaining: remainingCount,
    percentage: completed ? 100 : 0,
  }
}

export default function CycleDraw({
  groupId,
  cycleId,
  drawData,
  orderData,
  isAdmin,
  isDraft,
}) {
  const [selectedOption, setSelectedOption] = useState('')

  const selectDrawMutation = useSelectCycleDrawOption(
    groupId,
    cycleId,
  )

  // The backend provides UUID tokens. These must never be replaced
  // with display numbers or generated by the frontend.
  const options = Array.isArray(drawData?.options)
    ? drawData.options
    : EMPTY_OPTIONS

  const hasSelected =
    drawData?.has_selected === true ||
    orderData?.my_draw_status?.has_selected === true

  const drawComplete =
    drawData?.draw_complete === true ||
    orderData?.draw_complete === true

  const progress = useMemo(
    () => getDrawProgress(drawData, orderData, options),
    [drawData, orderData, options],
  )

  const canSelect =
    Boolean(groupId) &&
    Boolean(cycleId) &&
    isDraft &&
    !hasSelected &&
    !drawComplete &&
    options.length > 0

  function handleSelect(event) {
    event.preventDefault()

    if (!selectedOption) {
      toast.error('Please choose your mystery card.')
      return
    }

    if (!options.includes(selectedOption)) {
      setSelectedOption('')
      toast.error(
        'This card is no longer available. Please choose another.',
      )
      return
    }

    if (!canSelect || selectDrawMutation.isPending) {
      return
    }

    selectDrawMutation.mutate(selectedOption, {
      onSuccess: () => {
        setSelectedOption('')
      },
    })
  }

  const selectedIndex = options.indexOf(selectedOption)

  return (
    <Card
      title="Your lucky draw"
      description="Choose your mystery card and receive your payout position through the fair draw managed by the system."
    >
      <div className="space-y-7">

        {/* Introduction */}
        <section className="relative overflow-hidden rounded-2xl border border-brand-600/20 bg-surface-secondary p-5 sm:p-7">
          <div className="pointer-events-none absolute -right-16 -top-16 h-52 w-52 rounded-full border border-brand-600/10" />
          <div className="pointer-events-none absolute -right-8 -top-8 h-36 w-36 rounded-full border border-brand-600/15" />

          <div className="relative space-y-5">
            <span className="inline-flex rounded-full border border-brand-600/25 bg-surface px-3 py-1.5 text-xs font-semibold tracking-wider text-brand-600">
              MERIGO CYCLE DRAW
            </span>

            <div className="max-w-2xl">
              <h3 className="text-2xl font-bold tracking-tight text-text sm:text-3xl">
                Your position begins with a choice.
              </h3>

              <p className="mt-3 text-sm leading-7 text-text-muted sm:text-base">
                Every participating member gets one opportunity to
                select an available mystery card. The backend securely
                assigns the corresponding payout position. No member
                can select the same position twice.
              </p>
            </div>

            <div className="grid gap-3 border-t border-border pt-5 sm:grid-cols-3">
              <div>
                <p className="text-sm font-semibold text-text">
                  Fair selection
                </p>
                <p className="mt-1 text-xs leading-5 text-text-muted">
                  Available positions are selected through the backend.
                </p>
              </div>

              <div>
                <p className="text-sm font-semibold text-text">
                  One selection
                </p>
                <p className="mt-1 text-xs leading-5 text-text-muted">
                  Each member can submit only one draw selection.
                </p>
              </div>

              <div>
                <p className="text-sm font-semibold text-text">
                  Secure results
                </p>
                <p className="mt-1 text-xs leading-5 text-text-muted">
                  Your position is revealed according to the draw rules.
                </p>
              </div>
            </div>
          </div>
        </section>

        {/* Draw status */}
        <section className="rounded-xl border border-border p-4 sm:p-5">
          <div className="flex flex-wrap items-center justify-between gap-4">
            <div>
              <p className="text-xs font-semibold uppercase tracking-wider text-text-muted">
                Draw progress
              </p>

              <div className="mt-2 flex items-center gap-2">
                <span
                  className={`h-2.5 w-2.5 rounded-full ${
                    drawComplete
                      ? 'bg-green-500'
                      : 'bg-amber-500'
                  }`}
                />

                <p className="font-semibold text-text">
                  {drawComplete ? 'Draw completed' : 'Draw in progress'}
                </p>
              </div>
            </div>

            <div className="text-right">
              <p className="text-xs text-text-muted">
                Available cards
              </p>

              <p className="mt-1 text-2xl font-bold tabular-nums text-text">
                {progress.remaining}
              </p>
            </div>
          </div>

          {progress.total !== null && (
            <div className="mt-5">
              <div className="mb-2 flex items-center justify-between text-xs text-text-muted">
                <span>Selections completed</span>
                <span className="font-semibold tabular-nums text-text">
                  {progress.completed} / {progress.total}
                </span>
              </div>

              <div
                className="h-2 overflow-hidden rounded-full bg-surface-secondary"
                role="progressbar"
                aria-label="Draw completion progress"
                aria-valuemin={0}
                aria-valuemax={progress.total}
                aria-valuenow={progress.completed}
              >
                <div
                  className="h-full rounded-full bg-brand-600 transition-all duration-500"
                  style={{ width: `${progress.percentage}%` }}
                />
              </div>
            </div>
          )}
        </section>

        {/* Completed draw */}
        {drawComplete ? (
          <section className="rounded-xl border border-green-500/30 bg-green-500/5 p-5 sm:p-6">
            <p className="font-semibold text-text">
              The lucky draw is complete.
            </p>

            <p className="mt-2 text-sm leading-7 text-text-muted">
              All participating members have completed their
              selections. The payout order can now proceed through
              the swap and finalization stages.
            </p>

            {isAdmin && (
              <p className="mt-3 text-sm leading-6 text-text-muted">
                As administrator, you can monitor position swaps
                and finalize the payout order when the backend
                confirms that the conditions have been satisfied.
              </p>
            )}
          </section>

        ) : hasSelected ? (

          /* Member already selected */
          <section className="rounded-xl border border-brand-600/25 bg-brand-600/5 p-5 sm:p-6">
            <p className="font-semibold text-text">
              Your selection has been recorded.
            </p>

            <p className="mt-2 text-sm leading-7 text-text-muted">
              You have already selected your mystery card.
              Your payout position will be revealed according
              to the cycle's draw process.
            </p>
          </section>

        ) : !isDraft ? (

          /* Draw closed */
          <section className="rounded-xl border border-border bg-surface-secondary p-5">
            <p className="font-semibold text-text">
              Draw selections are closed.
            </p>

            <p className="mt-2 text-sm leading-6 text-text-muted">
              This cycle is no longer in draft status. New draw
              selections cannot be submitted.
            </p>
          </section>

        ) : options.length === 0 ? (

          /* No available options */
          <section className="rounded-xl border border-border bg-surface-secondary p-6 text-center">
            <p className="font-semibold text-text">
              No mystery cards are currently available.
            </p>

            <p className="mt-2 text-sm leading-6 text-text-muted">
              The draw options may not have been generated yet,
              or all available positions may already have been selected.
            </p>
          </section>

        ) : (

          /* Available cards */
          <section className="space-y-5">
            <div className="text-center">
              <h3 className="text-xl font-bold text-text">
                Choose your mystery card
              </h3>

              <p className="mx-auto mt-2 max-w-lg text-sm leading-6 text-text-muted">
                Select one card. Your choice will be submitted
                securely and cannot be selected again.
              </p>
            </div>

            <div className="grid grid-cols-1 gap-4 sm:grid-cols-2 lg:grid-cols-3">
              {options.map((token, index) => {
                const isSelected = selectedOption === token
                const design = CARD_DESIGNS[
                  index % CARD_DESIGNS.length
                ]

                return (
                  <button
                    key={token}
                    type="button"
                    disabled={
                      !canSelect ||
                      selectDrawMutation.isPending
                    }
                    aria-pressed={isSelected}
                    aria-label={`Select mystery card ${index + 1}`}
                    onClick={() => setSelectedOption(token)}
                    className={`
                      group relative rounded-2xl border p-3 text-left
                      transition-all duration-200
                      focus:outline-none focus-visible:ring-2
                      focus-visible:ring-brand-600
                      focus-visible:ring-offset-2
                      focus-visible:ring-offset-surface
                      ${
                        isSelected
                          ? 'border-brand-600 bg-brand-600/5 shadow-md ring-2 ring-brand-600/20'
                          : 'border-border bg-surface hover:-translate-y-1 hover:border-brand-600/50 hover:shadow-md'
                      }
                      disabled:cursor-not-allowed
                      disabled:opacity-60
                      disabled:hover:translate-y-0
                    `}
                  >
                    <div
                      className={`
                        relative flex min-h-[180px] flex-col
                        items-center justify-center overflow-hidden
                        rounded-xl border p-5
                        ${design.pattern}
                      `}
                    >
                      <div
                        className={`h-24 w-24 rounded-full border border-brand-600/20 ${design.decoration}`}
                      />

                      <div className="pointer-events-none absolute inset-4 rounded-lg border border-brand-600/10" />

                      <p className="relative mt-5 text-xs font-bold tracking-[0.2em] text-brand-600">
                        MYSTERY CARD
                      </p>
                    </div>

                    <div className="flex items-center justify-between gap-3 px-2 py-4">
                      <div>
                        <p className="text-sm font-semibold text-text">
                          {design.label}
                        </p>

                        <p className="mt-1 text-xs text-text-muted">
                          {isSelected
                            ? 'Selected for confirmation'
                            : 'Select this card'}
                        </p>
                      </div>

                      <span
                        className={`
                          flex h-7 w-7 shrink-0 items-center
                          justify-center rounded-full border
                          text-sm font-semibold transition-colors
                          ${
                            isSelected
                              ? 'border-brand-600 bg-brand-600 text-white'
                              : 'border-border text-transparent'
                          }
                        `}
                      >
                        ✓
                      </span>
                    </div>
                  </button>
                )
              })}
            </div>

            {/* Confirmation */}
            <form
              onSubmit={handleSelect}
              className="rounded-xl border border-brand-600/25 bg-brand-600/5 p-5 sm:p-6"
            >
              <div className="flex flex-col gap-4 sm:flex-row sm:items-center sm:justify-between">
                <div>
                  <p className="font-semibold text-text">
                    {selectedOption
                      ? 'Your mystery card is selected.'
                      : 'Your selection is waiting.'}
                  </p>

                  <p className="mt-1 text-sm leading-6 text-text-muted">
                    {selectedOption
                      ? 'Confirm your choice to submit it to the backend.'
                      : 'Choose one available card to continue.'}
                  </p>
                </div>

                <Button
                  type="submit"
                  variant="primary"
                  disabled={
                    !selectedOption ||
                    !canSelect ||
                    selectDrawMutation.isPending
                  }
                >
                  {selectDrawMutation.isPending
                    ? 'Submitting...'
                    : 'Confirm my selection'}
                </Button>
              </div>
            </form>
          </section>
        )}

        {/* Administrator information */}
        {isAdmin && (
          <section className="border-t border-border pt-5">
            <p className="text-xs font-semibold uppercase tracking-wider text-text-muted">
              Administrator information
            </p>

            <p className="mt-2 text-sm leading-6 text-text-muted">
              Monitor the draw until all members have selected.
              After completion, manage position-swap requests and
              finalize the payout order only when the backend
              permits it.
            </p>
          </section>
        )}
      </div>
    </Card>
  )
}
